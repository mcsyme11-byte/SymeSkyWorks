"""Build the Syme Skyworks website pages.
© 2026 Malcolm Syme · mcsyme11@gmail.com

Each page's content lives in src/pages/<name>.html and starts with a JSON comment
(title, description, active menu item, options). The shared header, footer, icons and
seasonal pop-up live in src/partials/. Run from the repo root:

    python3 tools/build.py

and commit the generated <name>.html files in the repo root (GitHub Pages serves those).
Bump VERSION after changing assets/style.css or assets/site.js.
"""
import json, re, pathlib

VERSION = "20261123h"
BASE = "https://mcsyme11-byte.github.io/SymeSkyWorks/"
ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
part = lambda n: (SRC / "partials" / n).read_text(encoding="utf-8")
ICONS, HEADER, FOOTER, POPUP, LD = part("icons.svg"), part("header.html"), part("footer.html"), part("popup.html"), part("ld-json.html")
SERVICES_KEYS = {"drone", "construction", "gallery"}

def head(name, m):
    title = m["title"] if m.get("fulltitle") else f'{m["title"]} · Syme Skyworks'
    url = BASE + ("" if name == "index" else f"{name}.html")
    leaflet_css = '\n<link rel="stylesheet" href="assets/vendor/leaflet/leaflet.css">' if m.get("leaflet") else ""
    return f'''<!DOCTYPE html>
<!-- Syme Skyworks website · © 2026 Malcolm Syme · mcsyme11@gmail.com · All rights reserved. -->
<!-- Generated by tools/build.py from src/pages/{name}.html. Edit the source, then rebuild. -->
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title}</title>
<meta name="description" content="{m["description"]}">
<meta name="author" content="Malcolm Syme">
<meta name="copyright" content="© 2026 Malcolm Syme · mcsyme11@gmail.com">
<meta name="theme-color" content="#0F1520">
<link rel="canonical" href="{url}">
<meta property="og:type" content="website">
<meta property="og:site_name" content="Syme Skyworks">
<meta property="og:title" content="{title}">
<meta property="og:description" content="{m["description"]}">
<meta property="og:url" content="{url}">
<meta property="og:image" content="{BASE}assets/img/og-image.jpg">
<meta name="twitter:card" content="summary_large_image">
<link rel="icon" href="assets/icons/favicon.svg" type="image/svg+xml">
<link rel="icon" href="assets/icons/favicon.ico" sizes="16x16 32x32 48x48">
<link rel="apple-touch-icon" href="assets/icons/apple-touch-icon.png">
<link rel="manifest" href="site.webmanifest">{leaflet_css}
<link rel="stylesheet" href="assets/style.css?v={VERSION}">
{LD if m.get("ld") else ""}</head>'''

def header(active):
    h = HEADER
    if active in SERVICES_KEYS:
        h = h.replace('data-key="services"', 'data-key="services" data-active="true"')
    if active:
        h = h.replace(f'data-key="{active}"', f'data-key="{active}" aria-current="page"', 1)
    return h

pages = sorted((SRC / "pages").glob("*.html"))
for p in pages:
    name = p.stem
    raw = p.read_text(encoding="utf-8")
    meta = json.loads(re.match(r"<!--(.*?)-->", raw, re.S).group(1))
    body = raw[raw.index("-->") + 3:].strip("\n")
    main_cls = ' class="page-main"' if name != "index" else ""
    scripts = ('<script src="assets/vendor/leaflet/leaflet.js" defer></script>\n' if meta.get("leaflet") else "") + \
              f'<script src="assets/site.js?v={VERSION}" defer></script>'
    html = "\n".join([head(name, meta), "<body>", ICONS.strip(), "", header(meta.get("active", "")),
                      f'<main id="main"{main_cls}>', body, "</main>", "", POPUP.strip(), "", FOOTER.strip(), "", scripts,
                      "</body>", "</html>", ""])
    (ROOT / f"{name}.html").write_text(html, encoding="utf-8")
    print("built", f"{name}.html")
